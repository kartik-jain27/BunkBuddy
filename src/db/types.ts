/**
 * types.ts — domain objects returned by the repository layer.
 *
 * Rows are stored snake_case in SQLite; repo functions map them to these
 * camelCase shapes. Pure types only: no React, no I/O.
 */

import type { AttendanceStatus, Counts } from '../lib/attendance';

export interface Subject {
  id: string;
  name: string;
  color: string;
  initialPresent: number;
  initialTotal: number;
  sortOrder: number;
  createdAt: string;
  updatedAt: string;
}

/** A subject plus its derived counts (opening balance + live records). */
export type SubjectWithCounts = Subject & Counts;

export interface AttendanceRecord {
  id: string;
  subjectId: string;
  /** NULL for an "extra" class that has no timetable slot. */
  slotId: string | null;
  /** 'YYYY-MM-DD' local day key. */
  date: string;
  status: AttendanceStatus;
}

export interface Profile {
  id: string;
  displayName: string | null;
  targetPct: number;
  semesterStart: string | null;
  semesterEnd: string | null;
  onboarded: boolean;
}

export interface Holiday {
  id: string;
  /** 'YYYY-MM-DD' local day key. */
  date: string;
  label: string | null;
}

/** A subject created during a timetable scan "Replace" save. */
export interface NewSubject {
  /** Generated by the caller so drafts can reference the new subject. */
  id: string;
  name: string;
  color: string;
  initialPresent?: number;
  initialTotal?: number;
}

/** Everything needed to undo a cascade delete. */
export interface DeleteToken {
  subjectId: string;
  deletedAt: string;
  slotIds: string[];
  recordIds: string[];
  taskIds: string[];
}
